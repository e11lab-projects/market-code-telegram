        f"Original commentary by THE MARKET CODE, based on public reporting from "
        f"{a['source_name']}. Written with the help of AI. Educational only, not "
        f"financial advice.",
        f"មតិវិភាគដើមដោយ THE MARKET CODE ផ្អែកលើការរាយការណ៍សាធារណៈពី "
