def esc(s):
    return html.escape(str(s), quote=True)


def slugify(text):
    s = re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-")
    return s[:70].strip("-") or "story"


def bi(en, km, tag="span", cls=""):
    en = str(en)
    km = str(km).strip() if km else en
    extra = (" " + cls) if cls else ""
