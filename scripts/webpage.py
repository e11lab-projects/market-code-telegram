def card_text(a):
    parts = [
        a.get("headline", ""),
        a.get("teaser", ""),
        a.get("headline_km", ""),
        a.get("teaser_km", ""),
    ]
    return " ".join(parts).lower()


def render_index(articles):
    chips = (
        f'<button class="chip on" onclick="setImp(\'all\',this)">{bi(*UI["all"])}</button>'
    )
    for key in ("bullish", "bearish", "mixed"):
        en, km = IMPACT_LABELS[key]
        chips += f'<button class="chip" onclick="setImp(\'{key}\',this)">{bi(en, km)}</button>'

    cards = ""
    for a in articles[:100]:
        en, km = IMPACT_LABELS.get(a.get("impact", ""), ("", ""))
        mini = f'<span class="mini">{bi(en, km)}</span>' if en else ""
        cards += (
            f'<a class="card" href="news/{esc(a["slug"])}.html" '
            f'data-impact="{esc(a.get("impact", ""))}" data-text="{esc(card_text(a))}">'
            f'<img src="news/{esc(a["slug"])}.jpg" alt="" loading="lazy">'
            f'<div class="txt"><span class="meta">{esc(a["date"])}</span>{mini}'
            f'<h2>{bi(a["headline"], a.get("headline_km", ""))}</h2>'
            f'{bi(a["teaser"], a.get("teaser_km", ""), "p")}</div></a>'
        )
    body = (
        '<section class="hero">'
        f'<h1>{bi(*UI["hero_title"])}</h1>'
        f'{bi(*UI["hero_sub"], "p", "lead")}'
        f'<p><a class="btn" href="{CHANNEL_URL}" target="_blank" rel="noopener">{bi(*UI["join"])}</a></p>'
        "</section>"
        '<div class="tools">'
        '<input id="q" type="search" placeholder="Search · ស្វែងរក" oninput="applyFilter()">'
        f"{chips}</div>"
        f'<div class="grid" id="grid">{cards}</div>'
        f'<p class="note" id="none" style="display:none">{bi(*UI["no_results"])}</p>'
    )
    return page(
        "Gold & Global Economy News | E11 Lab × THE MARKET CODE",
        body,
        "",
        "Daily news that moves gold (XAU/USD), in English and Khmer.",
        "",
        FILTER_JS,
    )


